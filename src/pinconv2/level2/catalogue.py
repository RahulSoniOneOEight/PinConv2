"""Source catalogue as data.

Every entry records what the source is, what it can supply, how it may be
reached, and what its licence allows. The catalogue is deliberately data rather
than prose: the licence gate validates it and tests assert the dangerous entries
stay blocked.
"""

from __future__ import annotations

from pydantic import Field

from ..models import StrictModel
from .models import LicenceClass


class SourceEntry(StrictModel):
    id: str = Field(pattern=r"^[a-z0-9][a-z0-9-]+$")
    name: str = Field(min_length=1, max_length=100)
    asset_types: list[str] = Field(min_length=1)
    licence_class: LicenceClass
    api: str | None = Field(default=None, max_length=300)
    scriptable: bool
    commercial_ok: bool
    attribution_required: bool = False
    aggregator: bool = False
    redistributable: bool = True
    notes: str = Field(min_length=1, max_length=400)
    blocked_reason: str | None = Field(default=None, max_length=300)

    def serves(self, asset_type: str) -> bool:
        return asset_type in self.asset_types


def _entry(**kwargs: object) -> SourceEntry:
    return SourceEntry.model_validate(kwargs)


