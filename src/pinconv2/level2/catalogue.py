SOURCE_MAP: dict[str, SourceEntry] = {source.id: source for source in SOURCES}


def entries_for(asset_type: str) -> list[SourceEntry]:
    return [source for source in SOURCES if source.serves(asset_type)]


def scriptable_sources(asset_type: str) -> list[SourceEntry]:
    return [
        source for source in entries_for(asset_type) if source.scriptable and not source.aggregator
    ]
